import { pgTable, serial, text, timestamp, boolean, numeric, date, integer, jsonb } from "drizzle-orm/pg-core";

export const dataSourcesTable = pgTable("data_sources", {
  id: serial("id").primaryKey(),
  sourceKey: text("source_key").notNull().unique(),
  displayName: text("display_name").notNull(),
  sourceType: text("source_type").notNull(),
  licenseStatus: text("license_status").notNull(),
  rightsReviewed: boolean("rights_reviewed").notNull().default(false),
  adapterVersion: text("adapter_version"),
  active: boolean("active").notNull().default(false),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

export const pointInTimeFactsTable = pgTable("point_in_time_facts", {
  id: serial("id").primaryKey(),
  isin: text("isin").notNull(),
  factKey: text("fact_key").notNull(),
  scope: text("scope").notNull().default("consolidated"),
  economicPeriodStart: date("economic_period_start", { mode: "string" }),
  economicPeriodEnd: date("economic_period_end", { mode: "string" }),
  periodEnd: date("period_end", { mode: "string" }).notNull(),
  filingDate: date("filing_date", { mode: "string" }),
  exchangeReceivedAt: timestamp("exchange_received_at", { withTimezone: true }),
  exchangeBroadcastAt: timestamp("exchange_broadcast_at", { withTimezone: true }),
  firstPublicAt: timestamp("first_public_at", { withTimezone: true }),
  systemReceivedAt: timestamp("system_received_at", { withTimezone: true }),
  processedAt: timestamp("processed_at", { withTimezone: true }),
  revisionAt: timestamp("revision_at", { withTimezone: true }),
  availableAt: timestamp("available_at", { withTimezone: true }).notNull(),
  validFrom: timestamp("valid_from", { withTimezone: true }),
  validTo: timestamp("valid_to", { withTimezone: true }),
  value: numeric("value", { precision: 24, scale: 8 }),
  reportedValue: numeric("reported_value", { precision: 24, scale: 8 }),
  reportedUnit: text("reported_unit"),
  reportedCurrency: text("reported_currency"),
  normalizedValue: numeric("normalized_value", { precision: 24, scale: 8 }),
  normalizedUnit: text("normalized_unit"),
  normalizedCurrency: text("normalized_currency"),
  conversionRate: numeric("conversion_rate", { precision: 20, scale: 10 }),
  conversionDate: date("conversion_date", { mode: "string" }),
  unit: text("unit"),
  sourceId: integer("source_id"),
  sourceGrade: text("source_grade"),
  sourceDocumentId: text("source_document_id"),
  sourceHash: text("source_hash"),
  documentHash: text("document_hash"),
  parserVersion: text("parser_version"),
  revisionOf: integer("revision_of"),
  reconciliationStatus: text("reconciliation_status").notNull().default("manual_review"),
  metadata: jsonb("metadata"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const corporateActionsTable = pgTable("corporate_actions", {
  id: serial("id").primaryKey(),
  isin: text("isin").notNull(),
  actionType: text("action_type").notNull(),
  exDate: date("ex_date", { mode: "string" }).notNull(),
  recordDate: date("record_date", { mode: "string" }),
  announcementDate: date("announcement_date", { mode: "string" }),
  actionDate: date("action_date", { mode: "string" }),
  ratioNumerator: numeric("ratio_numerator", { precision: 20, scale: 8 }),
  ratioDenominator: numeric("ratio_denominator", { precision: 20, scale: 8 }),
  cashAmount: numeric("cash_amount", { precision: 20, scale: 8 }),
  rawPriceFactor: numeric("raw_price_factor", { precision: 20, scale: 10 }),
  splitAdjustedFactor: numeric("split_adjusted_factor", { precision: 20, scale: 10 }),
  totalReturnFactor: numeric("total_return_factor", { precision: 20, scale: 10 }),
  basicSharesBefore: numeric("basic_shares_before", { precision: 20, scale: 8 }),
  basicSharesAfter: numeric("basic_shares_after", { precision: 20, scale: 8 }),
  dilutedSharesBefore: numeric("diluted_shares_before", { precision: 20, scale: 8 }),
  dilutedSharesAfter: numeric("diluted_shares_after", { precision: 20, scale: 8 }),
  sourceId: integer("source_id"),
  sourceDocumentId: text("source_document_id"),
  sourceHash: text("source_hash"),
  status: text("status").notNull().default("unvalidated"),
  validationNotes: text("validation_notes"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

