export const orderOutboxTable = pgTable("order_outbox", {
  id: serial("id").primaryKey(),
  outboxId: text("outbox_id").notNull().unique(),
  intentId: integer("intent_id").notNull(),
  accountId: text("account_id").notNull(),
  businessActionKey: text("business_action_key").notNull(),
  payload: jsonb("payload").notNull(),
  payloadHash: text("payload_hash").notNull(),
  status: text("status").notNull().default("prepared"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  transmittedAt: timestamp("transmitted_at", { withTimezone: true }),
  lastCheckedAt: timestamp("last_checked_at", { withTimezone: true }),
  brokerAcknowledgement: jsonb("broker_acknowledgement"),
}, (table) => ({
  accountActionUnique: uniqueIndex("order_outbox_account_action_unique").on(table.accountId, table.businessActionKey),
}));

