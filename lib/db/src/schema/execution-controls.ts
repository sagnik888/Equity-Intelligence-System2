export const riskPolicyTable = pgTable("risk_policies", {
  id: serial("id").primaryKey(),
  policyId: text("policy_id").notNull().unique(),
  version: text("version").notNull(),
  accountId: text("account_id").notNull(),
  strategyId: text("strategy_id").notNull(),
  instrumentClass: text("instrument_class").notNull(),
  maximumRiskFraction: numeric("maximum_risk_fraction", { precision: 12, scale: 8 }).notNull(),
  maximumDailyLossFraction: numeric("maximum_daily_loss_fraction", { precision: 12, scale: 8 }).notNull(),
  maximumDrawdownFraction: numeric("maximum_drawdown_fraction", { precision: 12, scale: 8 }).notNull(),
  effectiveFrom: timestamp("effective_from", { withTimezone: true }).notNull(),
  validUntil: timestamp("valid_until", { withTimezone: true }).notNull(),
  lastVerifiedAt: timestamp("last_verified_at", { withTimezone: true }),
  approvingIdentity: text("approving_identity"),
  approvalReference: text("approval_reference"),
  signedConfigurationHash: text("signed_configuration_hash"),
  signerKeyId: text("signer_key_id"),
  regulatoryReferences: jsonb("regulatory_references").$type<string[]>().notNull().default([]),
  brokerConfirmationReferences: jsonb("broker_confirmation_references").$type<string[]>().notNull().default([]),
  cryptographicVerificationStatus: text("cryptographic_verification_status").notNull().default("unavailable"),
  status: text("status").notNull().default("pending_review"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

